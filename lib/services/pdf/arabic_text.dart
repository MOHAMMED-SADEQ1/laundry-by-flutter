/// **مُطبِّع النصّ العربي قبل الرسم في PDF** — منطق خالص قابل للاختبار.
///
/// ## العيب الذي يعالجه (مُثبَت بالتجربة 2026-10-23)
/// حزمة `pdf` تُسقط **المسافة التي تسبق كلمة تبدأ بـ«لا»** (لام + ألف ⇒
/// الوصلة `لا`). فتُرسم «رمز الاستلام» هكذا: **«رمزالاستلام»** — كلمتان
/// ملتصقتان على ورقة تُعطى للزبون.
///
/// أُثبت بمسبار مباشر على الحزمة (`tool/_probe_arabic_space.dart`) بحجم 27pt
/// (حجم الإنتاج):
///
/// | النصّ | النتيجة |
/// |---|---|
/// | `رمز الاستلام` | ❌ `رمزالاستلام` |
/// | `رمز\u00A0الاستلام` (غير فاصلة) | ❌ `رمزالاستلام` — **تُبتلع أيضًا** |
/// | `رمز\u2009الاستلام` (رقيقة) | ❌ `رمزالاستلام` |
/// | `رمز  الاستلام` (مسافتان) | ✅ سليمة |
/// | `رمز استلام` (بلا وصلة) | ✅ سليمة |
/// | `رمز القطع` · `رمز الوردية` · `السلام عليكم` | ✅ سليمة |
///
/// ⇒ العيب محصور في النمط **ا ل ا** في أوّل الكلمة التالية، لا في العربية
/// عمومًا؛ والحلّ الوحيد الذي ينجو من التشكيل هو **مسافتان** (تُرسمان بمسافة
/// واحدة). ولذلك لا نستبدل كل المسافات — بل المسافة التي تسبق هذا النمط
/// فقط — فلا تتأثّر بقية النصوص ولا يمنع كسر السطر في `MultiPage`.
///
/// ## لماذا ملف مستقلّ؟
/// لأن الإصلاح مطلوب في مولّد الفاتورة ومولّد كشف الحساب معًا، ولا يجوز
/// استيراد أحدهما في الآخر. وهو خالص كي يُختبر بـ`dart run` بلا Flutter.
library;

class ArabicText {
  ArabicText._();

  /// البديل الذي ينجو من التشكيل: **مسافتان** تُرسمان بمسافة واحدة.
  ///
  /// ⚠️ لا تستخدم `\u00A0` (غير فاصلة) ولا `\u2009` (رقيقة): كلاهما يُبلع
  /// مثل المسافة العادية — مُثبَت بالمسبار.
  static const String spacer = '  ';

  /// الألف واللام — النمط الذي يبتلع المسافة قبلها هو **ا ل ا** (ألف · لام ·
  /// ألف)، أي كلمة تبدأ بـ«الا»: «الاستلام» · «الاسم» · «الأسعار».
  ///
  /// ⚠️ ليس لامًا ثم ألفًا كما قد يُظنّ: «لا يوجد» تُرسم سليمة، و«القطع»
  /// و«الوردية» سليمة أيضًا — العيب في الوصلة `لا` التي تتكوّن من اللام
  /// والألف **داخل** «الا» بعد الألف الأولى.
  static const String _alef = '\u0627';
  static const String _lam = '\u0644';

  /// يُصلح النصّ للرسم: يستبدل المسافة التي تسبق «لا» بمسافة غير فاصلة.
  ///
  /// لا يمسّ أي مسافة أخرى، ولا يغيّر ترتيب الحروف — فهو آمن على النصوص
  /// التي لا تحتاج إصلاحًا (يعيدها كما هي).
  static String safe(String input) {
    if (input.isEmpty || !input.contains(' ')) return input;
    final n = input.length;
    final out = StringBuffer();
    for (var i = 0; i < n; i++) {
      final c = input[i];
      // مسافة + ا + ل + ا ⇒ المسافة تُبلَع في الرسم ⇒ نضع مسافتين.
      //
      // ⚠️ `input[i - 1] != ' '` ضروري لعطالة التكرار: لو مُرِّر النصّ
      // المُصلَح مرّتين لأُضيفت مسافة ثالثة في كل مرّة (المسافة الثانية
      // تسبق «الا» أيضًا)، فتنمو الفراغات بلا سقف.
      if (c == ' ' &&
          (i == 0 || input[i - 1] != ' ') &&
          i + 3 < n &&
          input[i + 1] == _alef &&
          input[i + 2] == _lam &&
          input[i + 3] == _alef) {
        out.write(spacer);
      } else {
        out.write(c);
      }
    }
    return out.toString();
  }

  /// هل النصّ يحتاج إصلاحًا؟ (للتشخيص والاختبار)
  static bool needsFix(String input) => safe(input) != input;
}
