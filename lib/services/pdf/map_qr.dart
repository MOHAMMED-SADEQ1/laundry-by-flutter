/// **رابط موقع النشاط داخل رمز QR** — منطق خالص قابل للاختبار.
///
/// ## لماذا وحدة مستقلة؟
/// حقل `business_location` كان **مكتوبًا ولا يُقرأ**: يُحفظ من شاشة
/// «معلومات النشاط» ومن الإعداد الأولي، ثم لا يظهر في أي مستند ولا أي شاشة.
/// إعداد فعّال بلا مستهلك هو عيب صامت — يظنّ صاحب النشاط أنه أضاف موقعه
/// ولا يرى أثرًا. هنا يُصبح له مستهلك واحد: رمز QR أسفل الورقة.
///
/// ## لماذا لا يُمرَّر الرابط كما هو؟
/// لأن الرمز يُطبع على ورق ولا يمكن تصحيحه بعد الطباعة. رابط مكسور = رمز
/// يُقرأ ببرنامج ماسح ثم يفتح صفحة خطأ، وهو **أسوأ من غياب الرمز**: الزبون
/// يظنّ أن النشاط أخطأ في عنوانه. لذلك يُطبَّع الرابط ويُرفض ما لا يُفتح.
///
/// ## ما الذي يُقبل؟
///   • رابط كامل `https://maps.app.goo.gl/xxxx`
///   • رابط بلا بروتوكول `google.com/maps/place/...` ⇒ يُضاف `https://`
///   • رابط بروتوكول نسبي `//maps.google.com/?q=…` ⇒ يُضاف `https:`
///   • إحداثيات خام `24.7136,46.6753` ⇒ تُبنى لها صفحة خرائط
///
/// ## ما الذي يُرفض؟
/// الفراغ · ما ليس `http/https` (مثل `javascript:` أو `tel:`) · مضيف بلا
/// نقطة (`https://نشاطي`) · ما يتجاوز [maxLength].
///
/// 🚨 **حدّ الطول ليس تعسّفيًا**: عدد وحدات رمز QR يكبر مع طول المحتوى،
/// والرمز يُرسم بعرض ثابت على الورقة — فرابط طويل جدًا يُنتج وحدات أصغر من
/// أن تفصلها كاميرا هاتف على ورق مطبوع. القطع هنا **صريح ومقصود**: لا نطبع
/// رمزًا لا يُقرأ. روابط مشاركة خرائط جوجل الحقيقية أقلّ من 120 حرفًا بكثير.
library;

class MapQr {
  MapQr._();

  /// أقصى طول مقبول للرابط بعد التطبيع.
  static const int maxLength = 512;

  /// صفحة خرائط جوجل المبنية من إحداثيات خام.
  static const String coordsBase = 'https://www.google.com/maps?q=';

  /// `24.7136,46.6753` أو `24.7136, 46.6753` — إحداثيات فقط.
  static final RegExp _coords = RegExp(
    r'^-?\d{1,3}(?:\.\d+)?\s*,\s*-?\d{1,3}(?:\.\d+)?$',
  );

  /// يُطبّع الرابط ويعيده جاهزًا للترميز، أو `''` إن لم يصلح.
  ///
  /// **لا يرمي أبدًا** — يُستدعى داخل مولّد الـPDF (وفي عزل `compute`)،
  /// وفشل قراءة رابط لا يجوز أن يمنع طباعة فاتورة.
  static String resolve(Object? raw) {
    var v = '${raw ?? ''}'.trim();
    if (v.isEmpty) return '';

    // المسافة داخل الرابط تأتي من لصق نصّ من محرّر أو من رسالة. حذفها
    // يجعل `?q=24.7, 46.6` صالحًا بدل أن يُرفض بلا سبب مفهوم للمستخدم.
    v = v.replaceAll(RegExp(r'\s+'), '');
    if (v.isEmpty || v.length > maxLength) return '';

    // إحداثيات خام ⇒ صفحة خرائط. أكثر ما يلصقه الناس من تطبيق الخرائط
    // هو الزوج الرقمي نفسه لا رابطًا.
    if (_coords.hasMatch(v)) return '$coordsBase$v';

    if (v.startsWith('//')) {
      v = 'https:$v';
    } else if (!v.contains('://')) {
      v = 'https://$v';
    }

    final uri = Uri.tryParse(v);
    if (uri == null) return '';
    final scheme = uri.scheme.toLowerCase();
    if (scheme != 'http' && scheme != 'https') return '';

    final host = uri.host;
    if (!host.contains('.') || host.startsWith('.') || host.endsWith('.')) {
      return '';
    }
    // المضيف لا يحمل مسافة ولا محرفًا غير مسموح — `Uri` يتسامح أكثر من
    // المتصفّح، فنفحص هنا كي لا يُطبع رابط لا يفتحه الهاتف.
    if (host.contains(' ')) return '';

    return uri.toString();
  }

  /// هل يصلح هذا الرابط لبناء رمز؟
  static bool isValid(Object? raw) => resolve(raw).isNotEmpty;

  /// يقترح رابطًا صحيحًا حين يكون المُدخل **رمز مشاركة بلا نطاق**.
  ///
  /// ## الحالة الواقعية التي أُنشئت لها
  /// أبلغ المستخدم أن الرمز لا يُطبع، والقيمة المحفوظة كانت
  /// `https://ujfx8uiyhjfgksp8iuyrhjfsb`: بروتوكول + رمز مشاركة، **بلا نطاق**.
  /// وهي ليست رابطًا يفتحه هاتف، فلا يجوز ترميزها — لكن ترك المستخدم بلا
  /// مخرج أسوأ. فتُقترح الصيغة الكاملة.
  ///
  /// ## لماذا لا يُطبَّق الاقتراح تلقائيًا؟
  /// لأن تخمين رابط يفتح صفحة «غير موجود» أسوأ من عدم الطباعة: الزبون يظنّ
  /// أن النشاط أخطأ في عنوانه. الاقتراح يُعرَض على المستخدم **بزرّ** ويقرّر.
  ///
  /// يعيد `''` إن كان المُدخل صالحًا أصلًا (لا اقتراح) أو لا يشبه رمز مشاركة.
  static String repair(Object? raw) {
    final original = '${raw ?? ''}'.trim();
    if (original.isEmpty) return '';
    if (isValid(original)) return '';

    var v = original.replaceAll(RegExp(r'\s+'), '');
    // نزع البروتوكول ثم `//` ثم `www.` — بأي ترتيب وردت.
    v = v.replaceFirst(RegExp(r'^[a-zA-Z][a-zA-Z0-9+.\-]*://'), '');
    if (v.startsWith('//')) v = v.substring(2);
    if (v.toLowerCase().startsWith('www.')) v = v.substring(4);
    // بقي مسار أو نطاق ⇒ ليس رمزًا مجرّدًا، لا نخمّن.
    if (v.contains('/') || v.contains('.') || v.contains('?')) return '';

    // رمز مشاركة جوجل: حروف وأرقام و`-`/`_` فقط، بطول معقول.
    if (!RegExp(r'^[A-Za-z0-9_-]{5,64}$').hasMatch(v)) return '';
    return 'https://maps.app.goo.gl/$v';
  }

  /// هل يبدو رابط خرائط جوجل؟ — **للتنبيه في الواجهة لا للمنع**.
  ///
  /// لا نمنع روابط أخرى (قد يستعمل النشاط خدمة خرائط محلية)، لكن ننبّه
  /// صاحب النشاط إن أدخل رابطًا لا يشبه الخرائط كي لا يُطبع رمز مضلِّل.
  static bool looksLikeMaps(Object? raw) {
    final v = resolve(raw);
    if (v.isEmpty) return false;
    final host = (Uri.tryParse(v)?.host ?? '').toLowerCase();
    return host.contains('google') ||
        host.contains('goo.gl') ||
        host.contains('g.co') ||
        host.contains('maps');
  }
}
