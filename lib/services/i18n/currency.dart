/// رمز العملة المعروض في الواجهات — **يتبع لغة النظام**.
///
/// المشكلة التي يحلّها: كان `ر.س` مكتوبًا حرفيًّا في أكثر من مئة موضع، فيظهر
/// داخل جملة إنجليزية (`Paid 120.00 ر.س`) حتى بعد تعريب الواجهة كلها. الرمز
/// ليس اسم علم بل وحدة قياس، فحقّه أن يُترجم مع الجملة التي حوله.
///
/// القاعدة:
///   • الواجهة عربية ⇒ `ر.س` كما كتبه المستخدم.
///   • الواجهة إنجليزية ⇒ `SAR` (رمز ISO 4217) بدل الحرف العربي.
///   • أي رمز آخر يضبطه المستخدم في خيار «العملة» (`$`، `EUR`، `د.إ`…) يمرّ
///     كما هو في اللغتين — لا نفسّره ولا نبدّله، فهو اختيار صريح منه.
///
/// **لماذا `tr` لا `Currency.of(setting)`:** قراءة الإعداد في كل بناء واجهة
/// تعني رحلة إلى `SharedPreferences` لكل سطر مالي. الرمز المعروض ثابت ما دامت
/// اللغة ثابتة، فالمصدر هنا قاموس الترجمة (ذاكرة) لا الإعداد (قرص).
library;

import 'package:laundry/services/i18n/l10n.dart';

class Currency {
  const Currency._();

  /// الرمز العربي الافتراضي — مفتاح الترجمة نفسه.
  static const String sar = 'ر.س';

  /// صيغة كاملة شائعة في الرسائل («ريال»).
  static const String riyal = 'ريال';

  /// الرمز المعروض الآن، بلغة الواجهة الحالية.
  static String get symbol => tr(sar);

  /// يُعيد رمزًا مخزَّنًا (من الإعدادات) بصورته المعروضة.
  ///
  /// الفارغ يسقط للرمز الحالي؛ والعربي الافتراضي يُترجم؛ وما عداه يبقى.
  static String of(String? stored) {
    final s = (stored ?? '').trim();
    if (s.isEmpty) return symbol;
    if (s == sar || s == riyal) return symbol;
    return s;
  }
}
