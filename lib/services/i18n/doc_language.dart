/// **لغة المستندات المطبوعة** — منطق خالص (بلا Flutter ولا قاعدة بيانات).
///
/// مصدر واحد لقرار واحد: بأي لغة تُطبع الفاتورة · كشف الحساب · ملخص الوردية ·
/// ورقة المغسلة.
///
/// ## لماذا نوع منفصل عن [AppLanguage]؟
/// لأن قرار **لغة الشاشة** وقرار **لغة الورقة** قراران مختلفان تجاريًّا
/// ونظاميًّا:
///   • نشاط يعمل بكاشير يقرأ الإنجليزية ويطبع فاتورة عربية لعملائه.
///   • نشاط آخر واجهته عربية وموظّف الاستقبال يطبع نسخًا إنجليزية للزوّار.
/// ربط الورقة بلغة الشاشة كان يعني أن **تبديل لغة الواجهة يغيّر الفاتورة
/// الضريبية** — وهذا خطأ: الفاتورة مستند مالي له لغة يجب أن يحكمها إعداد
/// صريح، لا زرّ لغة في الشريط العلوي.
///
/// ⚠️ **لا يُشتقّ أي شيء هنا من `L10n`**: هذا النوع يُقرأ داخل `compute`
/// (عزل مستقلّ) حيث الحالة العامة للترجمة غير موجودة أصلًا.
library;

/// لغة طباعة المستندات.
enum DocLanguage {
  /// العربية — الاتجاه من اليمين لليسار. **الافتراضي** لأنها اللغة المطلوبة
  /// نظامًا في الفاتورة الضريبية السعودية.
  arabic('ar', 'العربية', 'Arabic'),

  /// الإنجليزية — الاتجاه من اليسار لليمين.
  english('en', 'English', 'English');

  const DocLanguage(this.code, this.label, this.labelEn);

  /// الكود المخزَّن في `settings.doc_language` (`ar` · `en`).
  final String code;

  /// الاسم بالعربية (يُعرض في قائمة الإعدادات).
  final String label;

  /// الاسم بالإنجليزية.
  final String labelEn;

  /// هل اتجاه المستند من اليمين لليسار؟
  bool get isRtl => this == DocLanguage.arabic;

  /// هل المستند إنجليزي؟ (تُحقن خريطة الترجمة في الحمولة حينها فقط)
  bool get isEnglish => this == DocLanguage.english;

  /// الافتراضي عند غياب الإعداد أو قيمته المجهولة.
  static const DocLanguage defaultLanguage = DocLanguage.arabic;

  /// كل الأكواد بترتيب العرض — مصدر قائمة `choices` في سجل الإعدادات.
  static List<String> get codes =>
      values.map((v) => v.code).toList(growable: false);

  /// يحلّ قيمة مخزَّنة إلى لغة مستند.
  ///
  /// **لا يرمي أبدًا**: أي قيمة فارغة أو مجهولة (نسخة قديمة · كتابة يدوية
  /// في القاعدة) تُرجع [defaultLanguage] فلا تتعطّل الطباعة بسبب إعداد فاسد.
  static DocLanguage byCode(String? raw) {
    final code = (raw ?? '').trim().toLowerCase();
    for (final value in values) {
      if (value.code == code) return value;
    }
    return defaultLanguage;
  }
}
